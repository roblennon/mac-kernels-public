"""Apply the fallback rule to every cell at 2 to 16 rows and summarise the re-timed cells.

Rule, the same for every shape and dtype: a cell goes to F.linear only when the kernel is slower
than F.linear beyond the noise in every process that timed it, that is when the largest speedup
(F.linear median / kernel median) over those processes is below 1 - noise, where noise is the
largest deviation of an A/A or B/B ratio from 1 in any of them. Otherwise the kernel keeps it.

Each cell is judged on the timing of the config the table now holds: this round's re-time
(retime-*.json, two processes at 4 to 16 rows, three at 2 and 3 rows) for every cell whose config
changed and every 2- and 3-row cell, and the round-2 layer runs (../layers-run*.json, two to four
processes) for the cells whose config did not change.

python3 summarize_fixes.py   (no GPU; writes summary.json, tables.md and linear_cells.json)
"""
import json
import statistics
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROUND2 = HERE.parent
SHAPE_NAMES = {"q17_qo": "q/o", "q17_kv": "k/v", "q17_up": "gate/up", "q17_down": "down", "q17_head": "head",
               "q4b_up": "Qwen3-4B up", "llama7b_up": "Llama-7B up"}


def rows_from(paths):
    out = {}
    for p in paths:
        for r in json.loads(p.read_text())["rows"]:
            out.setdefault((r["dtype"], r["shape"], r["M"]), []).append((p.name, r))
    return out


def main():
    choice = json.loads((HERE / "selection.json").read_text())["choice"]
    previous = json.loads((HERE / "compare-previous.json").read_text())
    new = rows_from(sorted(HERE.glob("retime-*.json")))
    old = rows_from(sorted(ROUND2.glob("layers-run*.json")))
    cells, linear = [], {}
    for dtype, shapes in choice.items():
        for shape, ms in shapes.items():
            for M, cfg in sorted(ms.items(), key=lambda kv: int(kv[0])):
                M = int(M)
                retimed = (dtype, shape, M) in new
                runs = [(f, r) for f, r in (new if retimed else old).get((dtype, shape, M), []) if r["config"] == cfg]
                if not runs:
                    raise SystemExit(f"no timing of {cfg} for {dtype} {shape} {M}")
                sp = [r["linear_over_multirow"] for _, r in runs]
                noise = max(max(abs(r["aa_ratio"] - 1), abs(r["bb_ratio"] - 1)) for _, r in runs)
                to_linear = max(sp) < 1 - noise
                lin_s = [s for _, r in runs for k in ("F.linear", "F.linear_again") for s in r["samples_us"][k]]
                ker_s = [s for _, r in runs for k in ("multirow", "multirow_again") for s in r["samples_us"][k]]
                cell = {"dtype": dtype, "shape": shape, "M": M, "config": cfg, "previous": previous[dtype][shape][str(M)],
                        "retimed": retimed, "processes": [f for f, _ in runs], "speedup": sp,
                        "aa": [r["aa_ratio"] for _, r in runs], "bb": [r["bb_ratio"] for _, r in runs],
                        "noise": noise, "routes_to": "F.linear" if to_linear else "kernel",
                        "linear_median_us": [r["median_us"]["F.linear"] for _, r in runs],
                        "kernel_median_us": [r["median_us"]["multirow"] for _, r in runs],
                        "fastest_us": {"F.linear": min(lin_s), "kernel": min(ker_s)},
                        "previous_over_new": [r.get("compare_over_multirow") for _, r in runs]}
                cells.append(cell)
                if to_linear:
                    linear.setdefault(dtype, {}).setdefault(shape, []).append(M)
    (HERE / "summary.json").write_text(json.dumps({"rule": __doc__.split("\n\n")[1], "cells": cells}, indent=1))
    (HERE / "linear_cells.json").write_text(json.dumps(linear, indent=1))

    def rng(xs, fmt="{:.2f}"):
        xs = [x for x in xs if x is not None]
        if not xs:
            return ""
        lo, hi = min(xs), max(xs)
        return fmt.format(lo) if fmt.format(lo) == fmt.format(hi) else f"{fmt.format(lo)}–{fmt.format(hi)}"

    lines = ["| dtype | shape | M | config | previous config | F.linear µs | kernel µs | fastest F.linear / kernel µs "
             "| speedup | A/A | B/B | previous / new | routed |", "|---|---|---:|---|---|---:|---:|---:|---:|---:|---:|---:|---|"]
    for c in cells:
        if not c["retimed"]:
            continue
        lines.append(f"| {c['dtype']} | {SHAPE_NAMES[c['shape']]} | {c['M']} | `{c['config']}` | `{c['previous']}` "
                     f"| {rng(c['linear_median_us'], '{:.1f}')} | {rng(c['kernel_median_us'], '{:.1f}')} "
                     f"| {c['fastest_us']['F.linear']:.1f} / {c['fastest_us']['kernel']:.1f} | {rng(c['speedup'])}x "
                     f"| {rng(c['aa'])} | {rng(c['bb'])} | {rng(c['previous_over_new'])} | {c['routes_to']} |")
    (HERE / "tables.md").write_text("# Re-timed cells\n\nGenerated by `summarize_fixes.py`. Ranges are over processes. "
                                    "\"previous / new\" is the previous table's config time over the new config's, "
                                    "in the same process (above 1: the new config is faster).\n\n" + "\n".join(lines) + "\n")
    re = [c for c in cells if c["retimed"]]
    print(f"{len(cells)} cells, {len(re)} re-timed, to F.linear: {linear}")
    pn = [x for c in re for x in c["previous_over_new"] if x is not None]
    print(f"previous/new over re-timed cells: median {statistics.median(pn):.3f}, min {min(pn):.3f}, max {max(pn):.3f}")


if __name__ == "__main__":
    main()
